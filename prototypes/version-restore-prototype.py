#!/usr/bin/env python3
"""PROTOTYPE — throwaway. Version restore by copying state FORWARD.

QUESTION
    Can "restore an earlier version" be built as *copy that version's canonical
    state forward into a NEW generation* (never rewind the pointer, ADR 0039),
    such that:
      C1 the restored canonical state is byte-identical to what was recorded,
      C2 a rebuild from the restored state is byte-identical to a rebuild from
         the original version (ADR 0041's determinism claim, end to end),
      C3 later versions survive — history stays monotonic,
      C4 nothing dead-ends afterwards: commit / export / verify still work,
      C5 GC does not eat the content a version points at (ADR 0042's premise).

WHAT THIS IS
    Real engine, real document, real store. The only prototype-specific bits are
    (a) a local `versions.jsonl` written by hand, and (b) a monkeypatched
    `_gc_abandoned` that honours a keep-list — that patch is the mechanism
    ADR 0042 proposes, prototyped here to see whether it is sufficient.

NOT PRODUCTION. No tests. Nothing is deleted. Scratch workdir is created fresh
under the path given (default: <repo-parent>/proto-version-restore).

RUN
    python prototypes/version-restore-prototype.py [scratch-dir]
"""
